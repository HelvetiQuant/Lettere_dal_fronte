@dataclass
class CanonicalEvent:
    """A canonical event in the V7 ontology."""
    event_id: str = ""
    name: str = ""
    event_type: str = ""
    conflict: str = "UNKNOWN"  # WWI|WWII|CONFLICTING
    start_date: str = ""
    end_date: str = ""
    location: str = ""
    description: str = ""
    parent_event_id: str = ""
    phases: List[Dict[str, Any]] = field(default_factory=list)
    aliases: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if not self.event_id:
            raw = json.dumps({
                "name": self.name,
                "type": self.event_type,
                "start": self.start_date,
                "end": self.end_date,
            }, sort_keys=True, ensure_ascii=False)
            self.event_id = f"evt_{hashlib.sha256(raw.encode()).hexdigest()[:16]}"

    def to_dict(self) -> dict:
        return asdict(self)


class EventOntology:
    """Canonical event ontology for V7.

    Provides:
      - Event type classification
      - Phase structuring
      - Relationship validation
      - Alias resolution
    """

    def __init__(self):
        self._events: Dict[str, CanonicalEvent] = {}
        self._aliases: Dict[str, str] = {}  # alias -> event_id

    def register_event(self, event: CanonicalEvent):
        self._events[event.event_id] = event
        for alias in event.aliases:
            self._aliases[alias.lower()] = event.event_id

    def get_event(self, event_id: str) -> Optional[CanonicalEvent]:
        return self._events.get(event_id)

    def resolve_alias(self, name: str) -> Optional[str]:
        """Resolve an event name or alias to its canonical event_id."""
        return self._aliases.get(name.lower())

    def classify_type(self, name: str, description: str = "") -> str:
        """Classify an event name into a canonical event type."""
        name_lower = name.lower()
        desc_lower = description.lower()

        type_keywords = {
            "battaglia": ["battaglia", "battle", "combat"],
            "offensiva": ["offensiva", "offensive", "push", "assalto"],
            "ritirata": ["ritirata", "retreat", "ripiegamento"],
            "avanzata": ["avanzata", "advance", "progresso"],
            "assedio": ["assedio", "siege", "accerchiamento"],
            "bombardamento": ["bombardamento", "bombing", "bombard"],
            "armistizio": ["armistizio", "armistice"],
            "dichiarazione_guerra": ["dichiarazione", "declaration"],
            "trattato_pace": ["trattato", "treaty", "pace", "peace"],
            "internamento": ["internamento", "internment", "prigionia"],
            "rimpatrio": ["rimpatrio", "repatriation", "ritorno"],
            "deportazione": ["deportazione", "deportation"],
            "liberazione": ["liberazione", "liberation"],
            "eccidio": ["eccidio", "massacre", "strage"],
        }

        for evt_type, keywords in type_keywords.items():
            for kw in keywords:
                if kw in name_lower or kw in desc_lower:
                    return evt_type

        return "altro"

    def all_events(self) -> Dict[str, CanonicalEvent]:
        return dict(self._events)


# ─── Aggregate definition registry ──────────────────────────────────────────

@dataclass
class AggregateDefinition:
    """A registered aggregate query definition.

    Aggregate queries are DETERMINISTIC — they are defined in the registry
    and cannot be invented by the AI. The AI can only reference registered
    definitions by their ID.
    """
    definition_id: str = ""
    name: str = ""
    description: str = ""
    query_template: str = ""  # SQL or structured query template
    parameters: List[Dict[str, Any]] = field(default_factory=list)
    output_schema: Dict[str, Any] = field(default_factory=dict)
    version: str = "1.0"
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())

    def __post_init__(self):
        if not self.definition_id:
            raw = json.dumps({
                "name": self.name,
                "template": self.query_template,
                "version": self.version,
            }, sort_keys=True, ensure_ascii=False)
            self.definition_id = f"agg_{hashlib.sha256(raw.encode()).hexdigest()[:16]}"

    def to_dict(self) -> dict:
        return asdict(self)


