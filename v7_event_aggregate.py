    def register(self, definition: AggregateDefinition):
        self._definitions[definition.definition_id] = definition

    def get(self, definition_id: str) -> Optional[AggregateDefinition]:
        return self._definitions.get(definition_id)

    def get_by_name(self, name: str) -> Optional[AggregateDefinition]:
        for d in self._definitions.values():
            if d.name == name:
                return d
        return None

    def all_definitions(self) -> Dict[str, AggregateDefinition]:
        return dict(self._definitions)

    def list_definition_ids(self) -> List[str]:
        return list(self._definitions.keys())

    def execute(self, definition_id: str, db_conn=None) -> Optional[Dict[str, Any]]:
        """Execute an aggregate query definition.

        Returns the aggregate result dict, or None if the definition doesn't exist.
        """
        definition = self.get(definition_id)
        if not definition:
            return None

        if not db_conn:
            from database import get_conn
            db_conn = get_conn()

        try:
            rows = db_conn.execute(definition.query_template).fetchall()
            results = [dict(r) for r in rows]
            return {
                "definition_id": definition_id,
                "name": definition.name,
                "description": definition.description,
                "results": results,
                "row_count": len(results),
            }
        except Exception as e:
            return {
                "definition_id": definition_id,
                "name": definition.name,
                "error": str(e),
                "results": [],
                "row_count": 0,
            }
        finally:
            if db_conn:
                db_conn.close()
