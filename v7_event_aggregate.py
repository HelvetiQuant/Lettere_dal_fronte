"""V7 Event Ontology & AggregateDefinitionRegistry.

This module defines:
  - EventOntology: canonical event types, phases, and relationships
  - AggregateDefinition: registered aggregate queries with deterministic definitions
  - AggregateDefinitionRegistry: versioned registry of aggregate definitions

Key principles:
  1. Aggregate queries are DETERMINISTIC — defined in a registry, not generated by AI
  2. Event types follow a canonical ontology (battle, offensive, retreat, armistice, etc.)
  3. Event phases are structured (preparation, execution, aftermath)
  4. The AI cannot invent aggregate definitions — it can only use registered ones
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field, asdict
from datetime import datetime
from typing import Dict, List, Optional, Any, Tuple


